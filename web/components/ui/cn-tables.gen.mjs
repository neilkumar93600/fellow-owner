// Compiles this project's class-merge config into static tables (cn-tables.ts), so the browser ships
// the small cn engine only, not cn/config's runtime compiler (~20 KB gzipped on every page).
// Edit THEME below, then run `node components/ui/cn-tables.gen.mjs` from web/. `--check` exits 1 when
// cn-tables.ts is stale and also proves the compiled engine merges exactly like createCn(THEME).
import { readFileSync, writeFileSync } from 'node:fs';
import { createCn as createRuntimeCn, defaultConfig, mergeConfigs } from 'cn/config';
import { compileToSource } from 'cn/compiler';

/**
 * The stock config reads custom roles such as `text-small` or `text-label` as colors and drops them
 * next to `text-ink`; with these they merge as font sizes, `rounded-card` as a radius and
 * `shadow-overlay` as a shadow, so a caller's className overrides a primitive's class of the same kind
 * and nothing else.
 */
export const THEME = {
  extend: {
    theme: {
      text: [
        'display',
        'h1',
        'h2',
        'stat',
        'count',
        'trend',
        'body',
        'label',
        'label-strong',
        'small',
        'small-strong',
        'caption',
        'hero',
        'section',
        'lead',
      ],
      radius: ['card', 'shell', 'panel', 'chip'],
      shadow: ['overlay', 'glass'],
      ease: ['out-quart', 'out-quint', 'out-expo'],
    },
  },
};

const out = new URL('./cn-tables.ts', import.meta.url);
const source = compileToSource(mergeConfigs(defaultConfig(), THEME), {
  lang: 'ts',
  banner: '// Generated by cn-tables.gen.mjs from its THEME. Do not edit by hand.',
});

if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== source) {
    console.error('cn-tables.ts is stale: run node components/ui/cn-tables.gen.mjs');
    process.exit(1);
  }
  // Every className string in the app, merged by both engines.
  const { createCn } = await import('cn/engine');
  const { default: tables } = await import(out.href);
  const compiled = createCn(tables);
  const runtime = createRuntimeCn(THEME);
  const { execSync } = await import('node:child_process');
  const files = execSync('git ls-files "*.tsx" "*.ts"', { encoding: 'utf8' }).trim().split('\n');
  const strings = new Set();
  for (const f of files) {
    for (const m of readFileSync(f, 'utf8').matchAll(/(['"`])((?:(?!\1)[^\n\$])*?\s(?:(?!\1)[^\n\$])*)\1/g)) {
      strings.add(m[2]);
    }
  }
  const all = [...strings];
  let bad = 0;
  for (let i = 0; i < all.length; i++) {
    for (const input of [all[i], `${all[i]} ${all[(i * 7 + 3) % all.length]}`]) {
      if (compiled(input) !== runtime(input)) {
        bad++;
        if (bad < 10) console.error('differs:', JSON.stringify(input));
      }
    }
  }
  console.log(`checked ${all.length * 2} class strings, ${bad} differ`);
  process.exit(bad ? 1 : 0);
}
writeFileSync(out, source);
console.log('wrote', out.pathname);
